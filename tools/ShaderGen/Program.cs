using System.Diagnostics;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;

// Compiles src/HyperPlot.Rendering.D3D11/Shaders/*.hlsl with the Windows SDK's fxc.exe and writes Shaders.g.cs beside them
// (design §5.7). Run from the repository root after changing a shader: dotnet run --project tools/ShaderGen
// The gate does not run this; a Core test checks that Shaders.g.cs carries the SHA-256 of the HLSL it was made from.
var root = args.Length > 0 ? args[0] : FindRoot();
var shaders = Path.Combine(root, "src", "HyperPlot.Rendering.D3D11", "Shaders");
var fxc = FindFxc();
if (fxc is null)
{
    Console.Error.WriteLine(
        "fxc.exe was not found: set HYPERPLOT_FXC, or install the Windows SDK under "
            + @"C:\Program Files (x86)\Windows Kits\10\bin\<version>\x64\fxc.exe."
    );
    return 1;
}

// Every entry point, in file and entry order; the generated properties follow this order.
(string File, string Entry, string Profile)[] entries =
[
    ("Glyph.hlsl", "GlyphPS", "ps_5_0"),
    ("Glyph.hlsl", "GlyphVS", "vs_5_0"),
    ("Line.hlsl", "BoundsVS", "vs_5_0"),
    ("Line.hlsl", "ColorPS", "ps_5_0"),
    ("Line.hlsl", "CoveragePS", "ps_5_0"),
    ("Line.hlsl", "SegmentVS", "vs_5_0"),
    ("Line.hlsl", "ZeroPS", "ps_5_0"),
];

var output = new StringBuilder();
output.AppendLine("// <auto-generated />");
output.AppendLine("// Written by tools/ShaderGen from Shaders/*.hlsl with fxc (design §5.7). Do not edit; run the generator.");
output.AppendLine("namespace HyperPlot.Rendering.D3D11;");
output.AppendLine();
output.AppendLine("/// <summary>The compiled shaders, as shader model 5.0 bytecode.</summary>");
output.AppendLine("internal static class Shaders");
output.AppendLine("{");
output.AppendLine("    /// <summary>The SHA-256 of the HLSL these were compiled from (see <c>HlslHash</c> in the Core tests).</summary>");
output.AppendLine(CultureInfo.InvariantCulture, $"    internal const string HlslSha256 = \"{HlslHash(shaders)}\";");
var temporary = Path.Combine(Path.GetTempPath(), $"shadergen-{Environment.ProcessId}.cso");
try
{
    foreach (var (file, entry, profile) in entries)
    {
        var arguments =
            $"/nologo /T {profile} /E {entry} /O3 /Qstrip_reflect /Qstrip_debug /Qstrip_priv /WX /Fo \"{temporary}\" \"{Path.Combine(shaders, file)}\"";
        using var process = Process.Start(new ProcessStartInfo(fxc, arguments) { RedirectStandardError = true, RedirectStandardOutput = true })!;
        var errors = process.StandardError.ReadToEnd();
        process.WaitForExit();
        if (process.ExitCode != 0)
        {
            Console.Error.WriteLine($"fxc failed on {file} {entry}:{Environment.NewLine}{errors}");
            return 1;
        }

        var bytes = File.ReadAllBytes(temporary);
        output.AppendLine();
        output.AppendLine(CultureInfo.InvariantCulture, $"    /// <summary>{entry} of {file} ({profile}).</summary>");
        output.AppendLine(CultureInfo.InvariantCulture, $"    internal static ReadOnlySpan<byte> {entry} =>");
        output.AppendLine("        [");
        for (var i = 0; i < bytes.Length; i += 16)
        {
            var line = string.Join(", ", bytes.Skip(i).Take(16).Select(b => $"0x{b:X2}"));
            output.AppendLine(CultureInfo.InvariantCulture, $"            {line},");
        }

        output.AppendLine("        ];");
    }
}
finally
{
    File.Delete(temporary);
}

output.AppendLine("}");
var target = Path.Combine(shaders, "Shaders.g.cs");
File.WriteAllText(target, output.ToString().ReplaceLineEndings("\n"));
Console.WriteLine($"Wrote {target} with {entries.Length} shaders.");
return 0;

static string FindRoot()
{
    for (var directory = new DirectoryInfo(Environment.CurrentDirectory); directory is not null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "HyperPlot.slnx")))
        {
            return directory.FullName;
        }
    }

    throw new InvalidOperationException("Run from inside the repository, or pass its root as the first argument.");
}

static string? FindFxc()
{
    if (Environment.GetEnvironmentVariable("HYPERPLOT_FXC") is { Length: > 0 } fromEnvironment)
    {
        return File.Exists(fromEnvironment) ? fromEnvironment : null;
    }

    var bin = @"C:\Program Files (x86)\Windows Kits\10\bin";
    if (!Directory.Exists(bin))
    {
        return null;
    }

    return Directory
        .GetDirectories(bin)
        .Select(d => (Version: Version.TryParse(Path.GetFileName(d), out var v) ? v : null, Path: Path.Combine(d, "x64", "fxc.exe")))
        .Where(c => c.Version is not null && File.Exists(c.Path))
        .OrderByDescending(c => c.Version)
        .Select(c => c.Path)
        .FirstOrDefault();
}

// The hash of every *.hlsl in ordinal name order: the name, a 0 byte, the text with LF line ends, a 0 byte. Line ends are
// made LF so that a checkout with CRLF gives the same hash. The Core test computes it the same way.
static string HlslHash(string directory)
{
    using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
    foreach (var path in Directory.GetFiles(directory, "*.hlsl").Order(StringComparer.Ordinal))
    {
        hash.AppendData(Encoding.UTF8.GetBytes(Path.GetFileName(path)));
        hash.AppendData([0]);
        hash.AppendData(Encoding.UTF8.GetBytes(File.ReadAllText(path).ReplaceLineEndings("\n")));
        hash.AppendData([0]);
    }

    return Convert.ToHexString(hash.GetHashAndReset());
}
