namespace HyperPlot.Tests;

/// <summary>
/// The entry point of the test executable: the one xunit generates, with one role before it. A test that needs a
/// process to kill starts this executable again with the switch of that role (<see cref="SpatialCopyChild"/>).
/// </summary>
internal static class Program
{
    /// <summary>Runs the role that the first argument names, or the tests.</summary>
    /// <param name="args">The command line.</param>
    /// <returns>The exit code of the process.</returns>
    public static int Main(string[] args)
    {
        if (args.Length > 0 && args[0] == SpatialCopyChild.Switch)
        {
            return SpatialCopyChild.Run(args.AsSpan(1));
        }

        // The two lines of xunit.v3.core.mtp-v2's generated entry point (XunitAutoGeneratedEntryPoint is off in the
        // project file so that this Main can come first).
        return args.Any(arg => arg is "--server" or "--internal-msbuild-node")
            ? Xunit
                .MicrosoftTestingPlatform.TestPlatformTestFramework.RunAsync(args, SelfRegisteredExtensions.AddSelfRegisteredExtensions)
                .GetAwaiter()
                .GetResult()
            : Xunit.Runner.InProc.SystemConsole.ConsoleRunner.Run(args).GetAwaiter().GetResult();
    }
}
